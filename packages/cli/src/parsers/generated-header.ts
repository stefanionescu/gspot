// Detects and writes generated-file notices.
import { HEADER_LINES_CHECKED, GENERATED_HEADER_LINE } from '#cli/config/generation/headers.ts';

/**
 * Detect the generated gspot marker in the opening comment lines.
 * @param text a file's opening text.
 * @returns whether the text carries the generated marker.
 */
export function hasGeneratedHeader(text: string): boolean {
    const lines = text.split('\n', HEADER_LINES_CHECKED);
    return lines.some((line) => GENERATED_HEADER_LINE.test(line));
}

/**
 * The file notice shared by generation and generated-file detection.
 * @returns the generated-file notice lines.
 */
export function generatedHeader(): string[] {
    return ['Generated by gspot from gspot.toml. To change it, edit gspot.toml and run gspot apply.'];
}
