// The loader metadata of a copied virtual environment names working-tree paths; these move them into the snapshot.
import { z } from 'zod';
import { run } from '#cli/platform/spawn.ts';
import { readdir, realpath } from 'node:fs/promises';
import { SelectionError } from '#cli/configurations/select.ts';
import type { ConfinedRoot, FileSnapshot } from '#cli/types/platform.ts';
import { basename, isAbsolute, join, posix, relative, resolve, sep } from 'node:path';
import type { PythonLauncher, RelocationContext } from '#cli/types/repository/revisions.ts';

const PARSE_TIMEOUT_MS = 30_000;
const EDITABLE_FINDER = /^(?:__editable__.*_finder|_editable_impl_.+)\.py$/u;

// Parse installed loader metadata without importing it or processing site packages.
const PYTHON_EDITABLE_PATHS = `import ast, json, sys
source = sys.stdin.read()
lines = source.encode("utf-8").splitlines(keepends=True)
paths = []
def add_path(entry):
    if not isinstance(entry, ast.Constant) or not isinstance(entry.value, str):
        raise ValueError("Editable paths must be literal strings")
    paths.append({"start": sum(map(len, lines[:entry.lineno - 1])) + entry.col_offset,
                  "end": sum(map(len, lines[:entry.end_lineno - 1])) + entry.end_col_offset,
                  "path": entry.value})
for statement in ast.parse(source).body:
    if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
        call = statement.value
        if isinstance(call.func, ast.Attribute) and isinstance(call.func.value, ast.Name) and call.func.value.id == "F" and call.func.attr == "map_module":
            if len(call.args) != 2 or call.keywords:
                raise ValueError("Editable module mappings must have two literal arguments")
            add_path(call.args[1])
        continue
    if isinstance(statement, ast.AnnAssign):
        targets = [statement.target]
    elif isinstance(statement, ast.Assign):
        targets = statement.targets
    else:
        continue
    if not any(isinstance(target, ast.Name) and target.id in ("MAPPING", "NAMESPACES") for target in targets):
        continue
    value = statement.value
    if not isinstance(value, ast.Dict):
        raise ValueError("Editable path metadata must be a literal dictionary")
    ast.literal_eval(value)
    for item in value.values:
        entries = item.elts if isinstance(item, (ast.List, ast.Tuple)) else [item]
        for entry in entries:
            add_path(entry)
print(json.dumps(paths))
`;
const PYTHON_PATH_SPANS = z.array(
    z.object({ start: z.number().int().nonnegative(), end: z.number().int().nonnegative(), path: z.string() }),
);

// Rewrites the paths an editable finder records, and drops the caches compiled from the old text.
async function relocateFinder(
    context: RelocationContext,
    launcher: PythonLauncher,
    path: string,
    current: FileSnapshot,
    relocatePath: (target: string) => string,
): Promise<void> {
    const { root, snapshot, selected, cancelSignal } = context;
    const parsed = await run(
        [join(snapshot, launcher.directory, launcher.names[0]), '-I', '-S', '-c', PYTHON_EDITABLE_PATHS],
        {
            cwd: snapshot,
            stdin: current.bytes.toString('utf8'),
            timeoutMs: PARSE_TIMEOUT_MS,
            ...(cancelSignal === undefined ? {} : { cancelSignal }),
        },
    );
    if (parsed.code !== 0)
        throw new SelectionError([
            'Cannot parse installed editable Python loader metadata. Reinstall dependencies for the selected revision.',
        ]);
    const spans = PYTHON_PATH_SPANS.parse(JSON.parse(parsed.stdout));
    let bytes = current.bytes;
    for (const span of spans.toSorted((left, right) => right.start - left.start)) {
        const relocated = relocatePath(resolve(root, launcher.sitePackages, span.path));
        bytes = Buffer.concat([
            bytes.subarray(0, span.start),
            Buffer.from(JSON.stringify(relocated)),
            bytes.subarray(span.end),
        ]);
    }
    if (!bytes.equals(current.bytes)) selected.write(path, { bytes, mode: current.mode }, current);
    removeCompiledCaches(selected, launcher.sitePackages, basename(path));
}

// Unchecked hash caches can retain working-tree paths after source relocation.
function removeCompiledCaches(selected: ConfinedRoot, sitePackages: string, finderName: string): void {
    const cache = posix.join(sitePackages, '__pycache__');
    const stem = `${finderName.slice(0, -'.py'.length)}.`;
    for (const name of selected.list(cache)) {
        if (!name.startsWith(stem) || !name.endsWith('.pyc')) continue;
        const cachedPath = posix.join(cache, name);
        const cached = selected.read(cachedPath);
        if (cached !== undefined) selected.remove(cachedPath, cached);
    }
}

// Rewrites each path a .pth file lists into the snapshot.
function relocatePathFile(
    context: RelocationContext,
    launcher: PythonLauncher,
    path: string,
    current: FileSnapshot,
    relocatePath: (target: string) => string,
): void {
    const text = current.bytes.toString('utf8');
    const relocated = text
        .split('\n')
        .map((line) => {
            if (line.startsWith('#') || line.trim() === '' || /^import[ \t]/u.test(line)) return line;
            return relocatePath(resolve(context.root, launcher.sitePackages, line.trimEnd()));
        })
        .join('\n');
    if (relocated !== text)
        context.selected.write(path, { bytes: Buffer.from(relocated), mode: current.mode }, current);
}

// Rewrites one site-packages file when it is an editable finder or a path file.
async function relocateSitePackageFile(
    context: RelocationContext,
    launcher: PythonLauncher,
    name: string,
    relocatePath: (target: string) => string,
): Promise<void> {
    const isFinder = EDITABLE_FINDER.test(name);
    if (!isFinder && !name.endsWith('.pth')) return;
    const path = posix.join(launcher.sitePackages, name);
    const current = context.selected.read(path);
    if (current === undefined) return;
    if (isFinder) await relocateFinder(context, launcher, path, current, relocatePath);
    else relocatePathFile(context, launcher, path, current, relocatePath);
}

/**
 * A function that moves a working-tree path into the snapshot, refusing paths outside the root or missing from it.
 * @param context the snapshot and its roots
 * @returns the relocation
 */
export async function pathRelocator(context: RelocationContext): Promise<(target: string) => string> {
    const { root, snapshot, selected } = context;
    const sourceRoots = [...new Set([root, await realpath(root)])];
    return (target) => {
        const local = sourceRoots
            .map((sourceRoot) => relative(sourceRoot, target))
            .find((candidate) => !isAbsolute(candidate) && candidate !== '..' && !candidate.startsWith(`..${sep}`));
        if (local === undefined)
            throw new SelectionError([
                'Installed Python path metadata references an external directory. Prepare isolated dependencies for the selected revision.',
            ]);
        if (local !== '' && selected.stat(local.split(sep).join('/')) === undefined)
            throw new SelectionError([
                'Installed Python path metadata references source missing from the selected revision. Install dependencies for that revision separately.',
            ]);
        return join(snapshot, local);
    };
}

/**
 * Rewrites the editable finders and path files of the copied environment to name snapshot paths.
 * @param context the snapshot, its roots, and cancellation
 * @param launcher the copied environment
 * @param relocatePath the relocation from pathRelocator
 */
export async function relocateSitePackages(
    context: RelocationContext,
    launcher: PythonLauncher,
    relocatePath: (target: string) => string,
): Promise<void> {
    const { snapshot, selected, cancelSignal } = context;
    if (selected.stat(launcher.sitePackages) === undefined) return;
    for (const entry of await readdir(join(snapshot, launcher.sitePackages), { withFileTypes: true })) {
        cancelSignal?.throwIfAborted();
        if (entry.isFile()) await relocateSitePackageFile(context, launcher, entry.name, relocatePath);
    }
}
