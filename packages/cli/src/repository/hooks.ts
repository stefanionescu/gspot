import { z } from 'zod';

export const HOOK_FILES = ['pre-commit', 'pre-push', 'commit-msg'] as const;

/** The files gspot owns in the hooks directory for its stages: each hook, its original sibling, and its manager copy. */
export const HOOK_ARTIFACTS: readonly string[] = HOOK_FILES.flatMap((hook) => [
    hook,
    `${hook}.gspot-original`,
    `${hook}.gspot-manager`,
]);

export const LEFTHOOK_MIN_VERSION = '2.0.13';

export const NATIVE_HOOK_MARKERS: Record<string, string> = {
    lefthook: 'call_lefthook run ',
    husky: '. "$(dirname "$0")/h"',
    'simple-git-hooks': 'if [ "$SKIP_SIMPLE_GIT_HOOKS" = "1" ]; then',
    'pre-commit': '# File generated by pre-commit: https://pre-commit.com',
};

export const hooksSchema = z.strictObject({
    tool: z
        .enum(['gspot', 'lefthook', 'husky', 'simple-git-hooks', 'pre-commit'])
        .describe('The tool that owns repository hooks.'),
    push: z
        .enum(['changed', 'all'])
        .default('changed')
        .describe('Check affected paths or the full tree of each pushed revision.'),
});

export const SIMPLE_GIT_HOOKS_DIRECTORY = '.gspot/integrations/simple-git-hooks';
