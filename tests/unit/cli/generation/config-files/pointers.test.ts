test.each(['', 'ios # app', 'AppTests', 'AppTests/Helpers'])(
    'XCTest folder pointers keep their SwiftLint overrides in scope "%s"',
    async (scope) => {
        await using sandbox = await testdir();
        const prefix = scope === '' ? '' : `${scope}/`;
        const folder = scope.startsWith('AppTests') ? scope : `${prefix}AppTests`;
        const child = `${prefix}ChildTests`;
        const scopeTable =
            scope === '' ? '' : `[[scope]]\npath = ${JSON.stringify(scope)}\nconfigurations = ["swift"]\n`;
        await createFileTree(sandbox.path, {
            'gspot.toml': buildSandboxSettings(scope === '' ? ['swift'] : [], {
                level: 'all',
                tables:
                    scopeTable +
                    `[[scope]]\npath = ${JSON.stringify(child)}\nconfigurations = ["swift"]\n` +
                    '[[scope]]\npath = "omitted"\n\nremoved_configurations = { value = ["swift"], reason = "This scope does not use Swift or its generated pointers." }\n',
            }),
            [`${folder}/Value.swift`]: 'import XCTest\n',
            [`${folder}/Deep/Value.swift`]: 'import XCTest\n',
            'omitted/AppTests/Value.swift': 'import XCTest\n',
            [`${child}/Value.swift`]: 'import XCTest\n',
        });
        const session = await openSession(sandbox.path);
        const files = generate(session).files;
        const pointer = files.find((file) => file.path === `${folder}/.swiftlint.yml`)!;
        const config = '.gspot/configurations/language/swift/swiftlint.yml';
        expect(parse(pointer.content)).toMatchObject({
            parent_config: `${'../'.repeat(folder.split('/').length)}${config}`,
        });
        expect(pointer.content).toStartWith('# Generated by gspot ');
        expect(files.filter((file) => file.path === pointer.path)).toHaveLength(1);
        expect(files.some((file) => file.path === `${folder}/Deep/.swiftlint.yml`)).toBe(false);
        expect(parse(files.find((file) => file.path === config)!.content)).toHaveProperty(
            'unused_import.always_keep_imports',
            [],
        );
        expect(files.find((file) => file.path === `${prefix}.swiftlint.yml`)!.content).toContain('parent_config:');
        expect(files.some((file) => file.path === 'omitted/AppTests/.swiftlint.yml')).toBe(false);
        const childConfig = getConfigFileTarget(
            child,
            session.configurations.get('swift')!.configFiles.find(({ tool }) => tool.includes('swiftlint'))!,
            getConfigFiles(session).targets,
        );
        const childPointer =
            files.find((file) => file.path === `${child}/.swiftlint.yml`) ??
            files.find((file) => file.path === `${prefix}.swiftlint.yml`)!;
        expect(files.some(({ path }) => path === childConfig)).toBe(true);
        expect(parse(childPointer.content)).toMatchObject({
            parent_config:
                (posix.dirname(childPointer.path) === '.' ? './' : '') +
                posix.relative(posix.dirname(childPointer.path), childConfig),
        });
        expect(parse(childPointer.content)).toHaveProperty('disabled_rules');
    },
);

test.each(['javascript'])(
    'JavaScript pointers import modules from folders with URI characters and Unicode',
    async (configurationName) => {
        await using sandbox = await testdir({
            'gspot.toml': buildSandboxSettings([...new Set([configurationName, 'javascript'])]),
        });

        const session = await openSession(sandbox.path);
        const configuration = session.configurations.get(configurationName)!;
        const configFile = configuration.configFiles
            .filter((file): file is WholeConfigFile => file.source !== undefined)
            .find((file) => file.pointer?.body.includes('{target_module}') === true)!;
        // Windows file names cannot contain a question mark.
        const components = MODULE_PATHS.filter((component) => !isWindows || !component.includes('?'));
        const paths = [];
        for (const [index, component] of components.entries()) {
            const target = `generated/${component}/owner.mjs`;
            const [output] = buildPointerFiles(
                {
                    session,
                    configuration,
                    scope: session.scopes[0]!,
                },
                { ...configFile, pointer: { ...configFile.pointer!, path: `entry-${String(index)}.mjs` } },
                target,
            );
            await createFileTree(sandbox.path, {
                [target]: `export default ${JSON.stringify(MODULE_VALUE)};\n`,
                [output!.path]: output!.content,
            });
            paths.push(pathToFileURL(join(sandbox.path, output!.path)).href);
        }
        const toolResult = await runCommand(
            [
                'node',
                '-e',
                'process.stdout.write(JSON.stringify(await Promise.all(process.argv.slice(1).map(async (path) => (await import(path)).default))));',
                ...paths,
            ],
            { cwd: sandbox.path },
        );
        expect(toolResult.code, toolResult.stderr).toBe(0);
        expect(JSON.parse(toolResult.stdout)).toStrictEqual(components.map(() => MODULE_VALUE));
    },
);

test('a scope gets its own markdownlint pointer only when its rules differ from the root', async () => {
    await using sandbox = await testdir({
        'gspot.toml': buildSandboxSettings(['markdown'], { tables: MARKDOWNLINT_SCOPE_TABLES }),
        'README.md': '# Root\n',
        'same/README.md': '# Same\n',
        'other/README.md': '# Other\n',
    });

    const paths = generate(await openSession(sandbox.path)).files.map(({ path }) => path);

    expect(paths).toContain('.markdownlint.jsonc');
    expect(paths).not.toContain('same/.markdownlint.jsonc');
    expect(paths).toContain('other/.markdownlint.jsonc');
});
