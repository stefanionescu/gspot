test('the generated GitHub workflow passes actionlint', async () => {
    await using sandbox = await testdir();
    await createFileTree(sandbox.path, { 'README.md': '# Workflow test\n' });
    commitAll(sandbox.path);
    const environment = { PATH: toolsPath() };
    await initRepository(sandbox.path, buildInitArguments(['github-actions']), environment);
    const selected = await spawnGspot(sandbox.path, ['set', 'level', 'all'], environment);
    expect(selected.code, selected.stdout + selected.stderr).toBe(0);
    const ci = await spawnGspot(sandbox.path, ['set', 'ci.enabled', 'true'], environment);
    expect(ci.code, ci.stdout + ci.stderr).toBe(0);
    const workflow = join(sandbox.path, '.github/workflows/gspot.yml');
    expect(await Bun.file(workflow).exists()).toBe(true);
    const emitted = await readFile(workflow);
    const headerEnd = emitted.indexOf('\n');
    expect(emitted.subarray(0, headerEnd).toString('utf8')).toMatch(/^# Generated by gspot /u);
    const payload = emitted.subarray(headerEnd + 1);
    await createFileTree(sandbox.path, { '.github/workflows/accepted.yml': payload.toString('utf8') });
    expect(await readFile(join(sandbox.path, '.github/workflows/accepted.yml'))).toEqual(payload);
    const session = await openSession(sandbox.path);
    expect(session.repository.files.find((file) => file.path === '.github/workflows/accepted.yml')).toMatchObject({
        kind: 'source',
    });
    const result = await spawnGspot(
        sandbox.path,
        ['check', '--only', 'github-actions/actionlint', '--json'],
        environment,
    );
    expect(result.code, result.stderr + result.stdout).toBe(0);
    expect(await readFile(workflow)).toEqual(emitted);
    expect((JSON.parse(result.stdout) as RunReport).checks).toMatchObject([
        { check: 'github-actions/actionlint', status: 'passed', findings: [] },
    ]);
});
// Runs the pinned Actionlint check over the repository's current authored workflows.
async function runActionlint(root: string) {
    const result = await spawnGspot(root, ['check', '--only', 'github-actions/actionlint', '--json']);
    return (JSON.parse(result.stdout) as RunReport).checks[0]!;
}

// GitHub self-repository references use $/. The pinned Actionlint needs their local spelling.
test('actionlint reports a missing required input of a same-repository reusable workflow and keeps your files', async () => {
    await using sandbox = await testdir();
    const workflow = `on: workflow_dispatch
jobs:
  caller:
    uses: $/.github/workflows/called.yml
`;
    const called = `on:
  workflow_call:
    inputs:
      greeting:
        type: string
        required: true
jobs:
  greet:
    runs-on: ubuntu-latest
    steps:
      - run: echo hello
`;
    await createFileTree(sandbox.path, {
        'gspot.toml': settingsText(['github-actions']),
        '.github/workflows/caller.yml': workflow,
        '.github/workflows/called.yml': called,
    });
    const failed = await runActionlint(sandbox.path);
    expect(failed.status, JSON.stringify(failed)).toBe('failed');
    expect(failed.findings).toContainEqual(
        containing({
            file: '.github/workflows/caller.yml',
            line: 4,
            column: 11,
            rule: 'workflow-call',
            message: textContaining('input "greeting" is required'),
        }),
    );
    expect(await Bun.file(join(sandbox.path, '.github/workflows/caller.yml')).text()).toBe(workflow);
    await Bun.write(
        join(sandbox.path, '.github/workflows/caller.yml'),
        `${workflow}    with:\n      greeting: Hello\n`,
    );
    const result = await runActionlint(sandbox.path);
    expect(result.status).toBe('passed');
    expect(await Bun.file(join(sandbox.path, '.github/workflows/called.yml')).text()).toBe(called);
});

test('actionlint follows a YAML alias to a same-repository workflow and reports it missing until it exists', async () => {
    await using sandbox = await testdir();

    await createFileTree(sandbox.path, {
        'gspot.toml': settingsText(['github-actions']),
        '.github/workflows/caller.yml': `on: workflow_dispatch
env:
  WORKFLOW: &workflow $/.github/workflows/called.yml
jobs:
  caller:
    uses: *workflow
`,
    });
    const failed = await runActionlint(sandbox.path);
    expect(failed.status, JSON.stringify(failed)).toBe('failed');
    expect(failed.findings).toContainEqual(
        containing({
            file: '.github/workflows/caller.yml',
            line: 3,
            column: 13,
            rule: 'workflow-call',
            message: textContaining('could not read reusable workflow file'),
        }),
    );
    await Bun.write(
        join(sandbox.path, '.github/workflows/called.yml'),
        `on: workflow_call
jobs:
  greet:
    runs-on: ubuntu-latest
    steps:
      - run: echo hello
`,
    );
    const result = await runActionlint(sandbox.path);
    expect(result.status).toBe('passed');
    expect(await Bun.file(join(sandbox.path, '.github/workflows/caller.yml')).text()).toBe(`on: workflow_dispatch
env:
  WORKFLOW: &workflow $/.github/workflows/called.yml
jobs:
  caller:
    uses: *workflow
`);
});

test('zizmor checks composite actions in the root and a scope', async () => {
    const level = 'all' as const;
    await using sandbox = await testdir();

    await createFileTree(sandbox.path, {
        'gspot.toml': settingsText(['github-actions'], {
            level,
            tables: `[[scope]]
path = "app"

configurations = ["github-actions"]
`,
        }),
        '.github/workflows/build.yml': CHECKOUT_WORKFLOW,
        '.github/actions/greet/action.yml': COMPOSITE_ACTION,
        'app/.github/workflows/build.yml': CHECKOUT_WORKFLOW,
        'app/.github/actions/greet/action.yaml': COMPOSITE_ACTION,
    });
    await installToolProjects(sandbox.path);
    const failedCommand = await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/zizmor', '--json']);
    const failed = JSON.parse(failedCommand.stdout) as RunReport;
    expect(failed.exitCode, JSON.stringify(failed)).toBe(1);
    expect(failed.checks.flatMap(({ findings }) => findings).map(({ file, rule }) => ({ file, rule }))).toStrictEqual([
        { file: '.github/actions/greet/action.yml', rule: 'template-injection' },
        { file: 'app/.github/actions/greet/action.yaml', rule: 'template-injection' },
    ]);
    for (const path of ['.github/actions/greet/action.yml', 'app/.github/actions/greet/action.yaml'])
        await Bun.write(
            join(sandbox.path, path),
            COMPOSITE_ACTION.replace(
                '          run: echo "${{ inputs.message }}"',
                '          env:\n              MESSAGE: ${{ inputs.message }}\n          run: echo "$MESSAGE"',
            ),
        );
    const correctedCommand = await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/zizmor', '--json']);
    const corrected = JSON.parse(correctedCommand.stdout) as RunReport;
    expect(corrected.exitCode, JSON.stringify(corrected)).toBe(0);
    expect(await Bun.file(join(sandbox.path, '.github/workflows/build.yml')).text()).toBe(CHECKOUT_WORKFLOW);
});

