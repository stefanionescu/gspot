import { readFile, realpath, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from 'bun:test';

import { runChecks } from '#cli/engine/run.ts';
import { openSession } from '#cli/engine/session.ts';
import {
    ALLOWED_PACKAGE_CASES,
    GPL_PACKAGE,
    LICENSE_TABLES,
    MIT_PACKAGE,
} from '#tests/config/configurations/licenses.ts';
import { getBuiltInCheck, openFakeToolSession, planSandboxCheck } from '#tests/setup/cli/checks.ts';
import { buildRunOptions } from '#tests/setup/cli/run.ts';
import { buildSandboxSettings } from '#tests/setup/cli/settings.ts';
import { createGitSandbox } from '#tests/setup/sandboxes/repositories.ts';
import { fakeCommands } from '#tests/setup/system/fakes.ts';
import { buildProcessResult } from '#tests/setup/system/processes.ts';

async function runLicenseCheck(
    root: string,
    packages: ReadonlyArray<Record<'name' | 'version' | 'ecosystem', string> & { licenses: readonly string[] }>,
    lockfile = 'package-lock.json',
) {
    using resources = new DisposableStack();
    const stdout = JSON.stringify({
        results: [
            {
                source: { path: join(await realpath(root), lockfile), type: 'lockfile' },
                packages: packages.map(({ name, version, ecosystem, licenses }) => ({
                    package: { name, version, ecosystem },
                    license_violations: licenses,
                })),
            },
        ],
    });
    const session = await openFakeToolSession(root, ['osv-scanner'], resources);
    const spawn = resources.use(fakeCommands().mockResolvedValue(buildProcessResult({ code: 1, stdout })));
    const findings = await getBuiltInCheck('licenses/allowed')(session, planSandboxCheck(session, 'licenses/allowed'));
    return { findings, command: spawn.mock.calls[0]?.[0] ?? [] };
}

test('licenses/allowed reports a disallowed license of a locked package, on its lockfile', async () => {
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses'], { tables: LICENSE_TABLES }),
        'package-lock.json': '{}\n',
    });
    const { findings } = await runLicenseCheck(sandbox.path, [MIT_PACKAGE, GPL_PACKAGE]);
    expect(findings.map(({ file, line, rule, message }) => ({ file, line, rule, message }))).toStrictEqual([
        {
            file: 'package-lock.json',
            line: 1,
            rule: 'disallowed-license',
            message: expect.stringMatching(/strict@1\.0\.0.*GPL-3\.0-only/u) as string,
        },
    ]);
});

test('licenses/allowed reports a Python package on the line of its entry in uv.lock', async () => {
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses'], { tables: LICENSE_TABLES }),
        'uv.lock':
            'version = 1\n\n[[package]]\nname = "app"\ndependencies = [{ name = "strict" }]\n\n[[package]]\nname = "strict"\nversion = "1.0.0"\n',
    });
    const { findings } = await runLicenseCheck(sandbox.path, [{ ...GPL_PACKAGE, ecosystem: 'PyPI' }], 'uv.lock');
    expect(findings).toMatchObject([{ file: 'uv.lock', line: 8, rule: 'disallowed-license' }]);
});

test('licenses/allowed reports an ignore whose paths cover no lockfile, and accepts one that names a lockfile', async () => {
    const ignores = ['pyproject.toml', 'tools/uv.lock']
        .map((path) => `[[ignore]]\ncheck = "licenses/allowed"\npaths = ["${path}"]\nreason = "Reviewed by legal."\n`)
        .join('');
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses'], { tables: `${LICENSE_TABLES}${ignores}` }),
        'package-lock.json': '{}\n',
        'pyproject.toml': '[project]\nname = "app"\nversion = "1.0.0"\n',
        'tools/uv.lock': 'version = 1\n',
    });
    const settings = await readFile(join(sandbox.path, 'gspot.toml'), 'utf8');
    const { findings } = await runLicenseCheck(sandbox.path, [MIT_PACKAGE]);
    expect(findings).toMatchObject([
        {
            file: 'gspot.toml',
            line: settings.split('\n').indexOf('paths = ["pyproject.toml"]') - 1,
            rule: 'unmatched-ignore',
            message: expect.stringContaining('pyproject.toml') as string,
        },
    ]);
});

test('licenses/allowed asks for every package, sends the allowed list, and reads each lockfile of its scope at any size, apart from gspot, nested scopes, and ignored folders', async () => {
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses'], {
            tables: `${LICENSE_TABLES}[repository]\nmax_file_kilobytes = 0\n`,
            scopes: [{ path: 'app' }],
        }),
        'package-lock.json': '{}\n',
        'poetry.lock': '# This file is automatically @generated by Poetry and should not be changed by hand.\n',
        'app/package-lock.json': '{}\n',
        '.gspot/bun.lock': '',
        '.claude/worktrees/copy/package-lock.json': '{}\n',
    });
    await writeFile(join(sandbox.path, '.git/info/exclude'), '.claude/worktrees/\n');
    const { command } = await runLicenseCheck(sandbox.path, [MIT_PACKAGE]);
    expect(command).toContain('--all-packages');
    expect(command).toContain('--licenses=MIT,Apache-2.0');
    expect(command.filter((argument) => argument.startsWith('--lockfile='))).toStrictEqual([
        '--lockfile=:package-lock.json',
        '--lockfile=:poetry.lock',
    ]);
});

test.each([...ALLOWED_PACKAGE_CASES])(
    'an allowed_package record $name',
    async ({ record, lockedName, ecosystem, findings }) => {
        await using sandbox = await createGitSandbox({
            'gspot.toml': buildSandboxSettings(['licenses'], {
                tables: `${LICENSE_TABLES}[[licenses.allowed_package]]\n${record}reason = "Reviewed by legal."\n`,
            }),
            'package-lock.json': '{}\n',
        });
        const { findings: reported } = await runLicenseCheck(sandbox.path, [
            { ...GPL_PACKAGE, name: lockedName, ecosystem },
        ]);
        expect(reported.map(({ rule }) => rule)).toStrictEqual([...findings]);
    },
);

test('licenses/allowed stops on no locked package', async () => {
    using resources = new DisposableStack();
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses'], { tables: LICENSE_TABLES }),
        'package-lock.json': '{}\n',
    });
    const session = await openFakeToolSession(sandbox.path, ['osv-scanner'], resources);
    resources.use(fakeCommands().mockResolvedValue(buildProcessResult({ code: 0, stdout: '{"results":[]}' })));
    const { report } = await runChecks(session, buildRunOptions({ only: ['licenses/allowed'], stage: 'push' }));
    expect(report.checks).toMatchObject([{ check: 'licenses/allowed', status: 'missing' }]);
});

test('the check skips with a note while licenses.allowed is empty', async () => {
    await using sandbox = await createGitSandbox({
        'gspot.toml': buildSandboxSettings(['licenses']),
        'package-lock.json': '{}\n',
    });
    const { report } = await runChecks(
        await openSession(sandbox.path),
        buildRunOptions({ only: ['licenses/allowed'], stage: 'push' }),
    );
    expect(report.checks).toMatchObject([
        { check: 'licenses/allowed', status: 'skipped', note: expect.stringContaining('licenses.allowed') as string },
    ]);
});
