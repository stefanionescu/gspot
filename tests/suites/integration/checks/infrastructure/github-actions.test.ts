import { join } from 'node:path';
import { test, expect } from 'bun:test';
import { testdir, createFileTree } from 'testdirs';
import { matchFields } from '#tests/setup/matchers.ts';
import { commitAll } from '#tests/setup/system/git.ts';
import { readFile, writeFile } from 'node:fs/promises';
import { isOnDisk } from '#tests/setup/system/files.ts';
import { initSandbox } from '#tests/setup/sandboxes/create.ts';
import type { Explanation } from '#cli/types/commands/explain.ts';
import { buildSandboxSettings } from '#tests/setup/cli/settings.ts';
import { spawnGspot, parseCheckReport, installGeneratedTools } from '#tests/setup/cli/commands.ts';

import {
    COMPOSITE_ACTION,
    CHECKOUT_WORKFLOW,
    REQUIRED_INPUT_WORKFLOW,
} from '#tests/config/integration/checks/infrastructure/github-actions.ts';

test('the generated GitHub workflow passes actionlint', async () => {
    await using sandbox = await testdir({ 'README.md': '# Workflow test\n' });

    commitAll(sandbox.path);
    const environment = {};
    // The sandbox needs no tool project, because mise pins actionlint.
    await initSandbox(
        { root: sandbox.path, environment, run: spawnGspot },
        { configurations: ['github-actions'], install: false },
    );
    const selected = await spawnGspot(sandbox.path, ['set', 'level', 'all'], environment);
    expect(selected.code, selected.stdout + selected.stderr).toBe(0);
    const ci = await spawnGspot(sandbox.path, ['set', 'ci.enabled', 'true'], environment);
    expect(ci.code, ci.stdout + ci.stderr).toBe(0);
    const workflow = join(sandbox.path, '.github/workflows/gspot.yml');
    expect(await isOnDisk(workflow)).toBe(true);
    const generated = await readFile(workflow);
    const headerEnd = generated.indexOf('\n');
    expect(generated.subarray(0, headerEnd).toString('utf8')).toMatch(/^# Generated by gspot /u);
    const payload = generated.subarray(headerEnd + 1);
    await createFileTree(sandbox.path, { '.github/workflows/accepted.yml': payload.toString('utf8') });
    expect(await readFile(join(sandbox.path, '.github/workflows/accepted.yml'))).toEqual(payload);
    const explained = await spawnGspot(
        sandbox.path,
        ['explain', './.github/workflows/accepted.yml', '--json'],
        environment,
    );
    expect(explained.code, explained.stdout + explained.stderr).toBe(0);
    expect(JSON.parse(explained.stdout) as Explanation['data']).toMatchObject({
        kind: 'path',
        fileKind: 'source',
    });
    const result = parseCheckReport(
        await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/actionlint', '--json'], environment),
    );
    expect(result.code, result.stderr + result.stdout).toBe(0);
    expect(await readFile(workflow)).toEqual(generated);
    expect(result.report.checks).toMatchObject([
        { check: 'github-actions/actionlint', status: 'passed', findings: [] },
    ]);
});

// GitHub self-repository references use $/. The pinned Actionlint needs their local spelling.
test('actionlint reports a missing required input of a same-repository reusable workflow and keeps your files', async () => {
    await using sandbox = await testdir();
    const workflow = `on: workflow_dispatch
jobs:
  caller:
    uses: $/.github/workflows/called.yml
`;
    const called = REQUIRED_INPUT_WORKFLOW;
    await createFileTree(sandbox.path, {
        'gspot.toml': buildSandboxSettings(['github-actions']),
        '.github/workflows/caller.yml': workflow,
        '.github/workflows/called.yml': called,
    });
    const failed = parseCheckReport(
        await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/actionlint', '--json']),
    ).report.checks[0]!;
    expect(failed.status, JSON.stringify(failed)).toBe('failed');
    expect(failed.findings).toContainEqual(
        matchFields({
            file: '.github/workflows/caller.yml',
            line: 4,
            column: 11,
            rule: 'workflow-call',
            message: expect.stringContaining('input "greeting" is required') as string,
        }),
    );
    expect(await readFile(join(sandbox.path, '.github/workflows/caller.yml'), 'utf8')).toBe(workflow);
    await writeFile(
        join(sandbox.path, '.github/workflows/caller.yml'),
        `${workflow}    with:\n      greeting: Hello\n`,
    );
    const result = parseCheckReport(
        await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/actionlint', '--json']),
    ).report.checks[0]!;
    expect(result.status).toBe('passed');
    expect(await readFile(join(sandbox.path, '.github/workflows/called.yml'), 'utf8')).toBe(called);
});

test('zizmor checks composite actions in the root and a scope', async () => {
    const level = 'all' as const;
    await using sandbox = await testdir({
        'gspot.toml': buildSandboxSettings(['github-actions'], {
            level,
            scopes: [{ path: 'app', configurations: ['github-actions'] }],
        }),
        '.github/workflows/build.yml': CHECKOUT_WORKFLOW,
        '.github/actions/greet/action.yml': COMPOSITE_ACTION,
        'app/.github/workflows/build.yml': CHECKOUT_WORKFLOW,
        'app/.github/actions/greet/action.yaml': COMPOSITE_ACTION,
    });

    await installGeneratedTools(sandbox.path);
    const failedCommand = parseCheckReport(
        await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/zizmor', '--json']),
    );
    const failed = failedCommand.report;
    expect(failed.exitCode, JSON.stringify(failed)).toBe(1);
    expect(failed.checks.flatMap(({ findings }) => findings).map(({ file, rule }) => ({ file, rule }))).toStrictEqual([
        { file: '.github/actions/greet/action.yml', rule: 'template-injection' },
        { file: 'app/.github/actions/greet/action.yaml', rule: 'template-injection' },
    ]);
    for (const path of ['.github/actions/greet/action.yml', 'app/.github/actions/greet/action.yaml'])
        await writeFile(
            join(sandbox.path, path),
            COMPOSITE_ACTION.replace(
                '          run: echo "${{ inputs.message }}"',
                '          env:\n              MESSAGE: ${{ inputs.message }}\n          run: echo "$MESSAGE"',
            ),
        );
    const correctedCommand = parseCheckReport(
        await spawnGspot(sandbox.path, ['check', '--only', 'github-actions/zizmor', '--json']),
    );
    const corrected = correctedCommand.report;
    expect(corrected.exitCode, JSON.stringify(corrected)).toBe(0);
    expect(await readFile(join(sandbox.path, '.github/workflows/build.yml'), 'utf8')).toBe(CHECKOUT_WORKFLOW);
});
