import assert from 'node:assert/strict'
import { afterEach, beforeEach, describe, it } from 'bun:test'
import { MIXED_NATURES } from '@config/tests/repositories'
import { classify } from '@/coverage/classify'
import { compileSelector } from '@/settings/selector'
import { removeRepository, plantUncommitted } from '@tests/support/repository'
import type { PathAttributes } from 'types/coverage'
import type { ClassifyInputs } from 'types/measure'
import type { Declaration } from 'types/settings'

const NO_ATTRIBUTES: PathAttributes = { generated: false, vendored: false, notText: false, filter: null }

describe('classify', () => {
  let root = ''

  function inputs(extra: Partial<ClassifyInputs> = {}): ClassifyInputs {
    return { root, declarations: [], attributes: new Map(), frozen: new Set(), banners: [], ...extra }
  }

  beforeEach(async () => {
    root = await plantUncommitted('classify', MIXED_NATURES)
  })

  afterEach(async () => {
    await removeRepository(root)
  })

  it('treats an ordinary text file as source', async () => {
    const found = await classify('src/module.ts', inputs())
    assert.equal(found.nature, 'source')
    assert.equal(found.from, 'default')
  })

  it('reads a declaration naming a producer as generated, keeping the task name', async () => {
    const declaration: Declaration = {
      paths: compileSelector(['src/**'], 'test'),
      producedBy: 'db:gen:types',
    }
    const found = await classify('src/module.ts', inputs({ declarations: [declaration] }))
    assert.equal(found.nature, 'generated')
    assert.equal(found.producedBy, 'db:gen:types')
  })

  it('reads a declaration carrying only a reason as vendored, keeping the reason', async () => {
    const declaration: Declaration = {
      paths: compileSelector(['src/**'], 'test'),
      reason: 'Upstream source, patched only by rebase',
    }
    const found = await classify('src/module.ts', inputs({ declarations: [declaration] }))
    assert.equal(found.nature, 'vendored')
    assert.equal(found.reason, 'Upstream source, patched only by rebase')
  })

  it('lets a declaration outrank the git attribute', async () => {
    const attributes = new Map([['src/module.ts', { ...NO_ATTRIBUTES, vendored: true }]])
    const declaration: Declaration = {
      paths: compileSelector(['src/**'], 'test'),
      producedBy: 'db:gen:types',
    }
    const found = await classify('src/module.ts', inputs({ attributes, declarations: [declaration] }))
    assert.equal(found.nature, 'generated')
    assert.equal(found.from, 'declaration')
  })

  it('reads linguist-generated and linguist-vendored from git', async () => {
    const generated = new Map([['src/module.ts', { ...NO_ATTRIBUTES, generated: true }]])
    assert.equal((await classify('src/module.ts', inputs({ attributes: generated }))).nature, 'generated')

    const vendored = new Map([['src/module.ts', { ...NO_ATTRIBUTES, vendored: true }]])
    assert.equal((await classify('src/module.ts', inputs({ attributes: vendored }))).nature, 'vendored')
  })

  it('takes -text and filter=lfs as binary without reading the bytes', async () => {
    const notText = new Map([['src/module.ts', { ...NO_ATTRIBUTES, notText: true }]])
    assert.equal((await classify('src/module.ts', inputs({ attributes: notText }))).nature, 'binary')

    const lfs = new Map([['src/module.ts', { ...NO_ATTRIBUTES, filter: 'lfs' }]])
    assert.equal((await classify('src/module.ts', inputs({ attributes: lfs }))).nature, 'binary')
  })

  it('reads a banner a preset recognises as generated', async () => {
    const found = await classify('src/types.ts', inputs({ banners: ['@generated by the codegen'] }))
    assert.equal(found.nature, 'generated')
    assert.equal(found.from, 'banner')
  })

  it('sniffs a null byte as binary', async () => {
    const found = await classify('src/logo.png', inputs())
    assert.equal(found.nature, 'binary')
    assert.equal(found.from, 'content')
  })

  it('treats a path a preset froze as frozen', async () => {
    const found = await classify('src/module.ts', inputs({ frozen: new Set(['src/module.ts']) }))
    assert.equal(found.nature, 'frozen')
  })

  it('treats a file absent from the working tree as binary rather than guessing', async () => {
    const found = await classify('src/gone.ts', inputs())
    assert.equal(found.nature, 'binary')
  })
})
